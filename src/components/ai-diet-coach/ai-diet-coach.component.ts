  selector: 'app-ai-diet-coach',
  standalone: true,
  imports: [CommonModule, FormsModule],
  template: `
    <div class="space-y-6">
      <header>
        <h1 class="text-3xl font-bold text-white">AI Diet + Workout Coach</h1>
        <p class="text-gray-400">Get a personalized wellness plan generated by your AI Coach.</p>
      </header>

      @if (!hasApiKey()) {
        <div class="bg-red-900/50 border border-red-500/50 rounded-lg p-4 text-center">
          <p class="text-red-300">AI features are disabled. Please configure the NEXT_PUBLIC_GEMINI_API_KEY in your Vercel project settings and redeploy.</p>
        </div>
      }

      <!-- User Stats -->
      <div class="bg-[#0b0b12] p-4 rounded-lg border border-white/10">
        <h3 class="text-lg font-semibold text-gray-200 mb-3">Your Current Stats</h3>
        <div class="grid grid-cols-2 md:grid-cols-4 gap-4 text-center">
          <div>
            <p class="text-sm text-gray-400">Current Weight</p>
            <p class="text-xl font-bold text-[#00E0B8]">{{ currentWeightKg() ? currentWeightKg() + ' kg' : 'N/A' }}</p>
          </div>
          <div>
            <p class="text-sm text-gray-400">Height</p>
            <p class="text-xl font-bold text-white">{{ userHeightCm() ? userHeightCm() + ' cm' : 'N/A' }}</p>
          </div>
          <div>
            <p class="text-sm text-gray-400">BMI</p>
            <p class="text-xl font-bold text-[#7C5CFF]">{{ bmi() ?? 'N/A' }}</p>
          </div>
          <div>
            <p class="text-sm text-gray-400">Category</p>
            <p class="text-xl font-bold text-white">{{ bmiCategory() }}</p>
          </div>
        </div>
        @if (!currentWeightKg()) {
          <p class="text-xs text-center text-amber-500 mt-3">Log your weight in the 'Weight AI' section to see your stats.</p>
        }
      </div>


      <!-- Preferences Form -->
      <div class="bg-[#131321] p-6 rounded-lg border border-white/10">
        <form (ngSubmit)="generatePlan()">
          <div class="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
            <!-- Column 1 -->
            <div class="space-y-4">
              <div>
                <label for="language" class="block text-sm font-medium text-gray-300 mb-1">Language</label>
                <select id="language" [(ngModel)]="language" name="language" class="w-full bg-[#0b0b12] border border-gray-600 rounded-md p-3 text-white focus:outline-none focus:ring-2 focus:ring-[#7C5CFF]">
                  <option value="English">English</option>
                  <option value="Hindi">Hindi</option>
                  <option value="Gujarati">Gujarati</option>
                </select>
              </div>
              <div>
                <label for="dietType" class="block text-sm font-medium text-gray-300 mb-1">Dietary Preference</label>
                <select id="dietType" [(ngModel)]="dietType" name="dietType" class="w-full bg-[#0b0b12] border border-gray-600 rounded-md p-3 text-white focus:outline-none focus:ring-2 focus:ring-[#7C5CFF]">
                  <option value="Vegetarian">Vegetarian</option>
                  <option value="Non-Vegetarian">Non-Vegetarian</option>
                  <option value="Vegan">Vegan</option>
                  <option value="Keto">Keto</option>
                  <option value="Indian Traditional">Indian Traditional</option>
                </select>
              </div>
            </div>
            <!-- Column 2 -->
            <div class="space-y-4">
               <div>
                <label for="goal" class="block text-sm font-medium text-gray-300 mb-1">Primary Goal</label>
                <select id="goal" [(ngModel)]="dietGoal" name="goal" class="w-full bg-[#0b0b12] border border-gray-600 rounded-md p-3 text-white focus:outline-none focus:ring-2 focus:ring-[#7C5CFF]">
                  <option value="weight loss">Weight Loss</option>
                  <option value="muscle gain">Muscle Gain</option>
                  <option value="maintenance">Maintenance</option>
                  <option value="general health">General Health</option>
                </select>
              </div>
               <div>
                <label for="targetWeight" class="block text-sm font-medium text-gray-300 mb-1">Target Weight (kg)</label>
                <input id="targetWeight" type="number" [(ngModel)]="targetWeight" name="targetWeight" class="w-full bg-[#0b0b12] border border-gray-600 rounded-md p-3 text-white placeholder-gray-500 focus:outline-none focus:ring-2 focus:ring-[#7C5CFF]" placeholder="e.g., 75">
              </div>
            </div>
             <!-- Column 3 -->
             <div class="space-y-4">
                <div>
                  <label for="planType" class="block text-sm font-medium text-gray-300 mb-1">Plan Type</label>
                  <select id="planType" [(ngModel)]="planType" name="planType" class="w-full bg-[#0b0b12] border border-gray-600 rounded-md p-3 text-white focus:outline-none focus:ring-2 focus:ring-[#7C5CFF]">
                    <option value="diet">Diet Only</option>
                    <option value="diet-workout">Diet + Workout</option>
                    <option value="diet-workout-supplements">Diet + Workout + Supplements</option>
                  </select>
                </div>
                 <div>
                  <label for="planDuration" class="block text-sm font-medium text-gray-300 mb-1">Plan Duration</label>
                  <select id="planDuration" [(ngModel)]="planDuration" name="planDuration" class="w-full bg-[#0b0b12] border border-gray-600 rounded-md p-3 text-white focus:outline-none focus:ring-2 focus:ring-[#7C5CFF]">
                    <option value="1 month">1 Month</option>
                    <option value="3 months">3 Months</option>
                    <option value="9 months">9 Months</option>
                  </select>
                </div>
              </div>
          </div>
          <div class="mt-6">
            <label for="preferences" class="block text-sm font-medium text-gray-300 mb-1">Likes, Dislikes, Allergies</label>
            <textarea id="preferences" [(ngModel)]="preferences" name="preferences" rows="4" class="w-full bg-[#0b0b12] border border-gray-600 rounded-md p-3 text-white placeholder-gray-500 focus:outline-none focus:ring-2 focus:ring-[#7C5CFF]" placeholder="e.g., allergic to peanuts, dislike mushrooms, love spicy food"></textarea>
          </div>
          <div class="mt-6">
            <button type="submit" [disabled]="isLoading() || !hasApiKey()" class="w-full bg-[#7C5CFF] text-white px-5 py-3 rounded-md font-semibold hover:bg-[#6a48ff] disabled:bg-gray-600 disabled:cursor-not-allowed transition-colors">
              @if (isLoading()) {
                <i class="fa-solid fa-spinner fa-spin mr-2"></i>
                <span>Generating Plan...</span>
              } @else {
                <span>Generate My Wellness Plan</span>
              }
            </button>
          </div>
        </form>
      </div>

      <!-- AI Response -->
      @if(isLoading() || dietPlan()) {
        <section class="bg-[#131321] p-6 rounded-lg border border-white/10">
          <div class="flex justify-between items-center mb-4">
            <h2 class="text-xl font-semibold">Your AI-Generated Wellness Plan</h2>
            @if(dietPlan() && !isLoading()) {
              <button (click)="downloadAsPdf()" [disabled]="isDownloadingPdf()" class="px-4 py-2 bg-green-600/80 text-white rounded-md hover:bg-green-600 flex items-center justify-center gap-2 disabled:bg-green-600/40">
                @if (isDownloadingPdf()) {
                  <i class="fas fa-spinner fa-spin"></i> <span>Preparing...</span>
                } @else {
                  <i class="fas fa-file-pdf"></i> Download PDF
                }
              </button>
            }
          </div>
          @if (error()) {
            <p class="text-red-400">{{ error() }}</p>
          } @else {
            <div class="prose prose-sm md:prose-base prose-invert max-w-none space-y-4" [innerHTML]="sanitizedDietPlan()"></div>
          }
        </section>
      }
    </div>
  `,
  changeDetection: ChangeDetectionStrategy.OnPush,
